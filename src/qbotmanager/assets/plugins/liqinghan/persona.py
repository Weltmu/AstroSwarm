def extract_text(segments):
    parts = []
    if isinstance(segments, str):
        return segments
    for s in segments or []:
        t = s.get("type") if isinstance(s, dict) else None
        d = s.get("data", {}) if isinstance(s, dict) else {}
        if t == "text":
            parts.append(d.get("text", ""))
        elif t == "image":
            parts.append("[图片]")
        elif t in ("face", "sface"):
            parts.append("[表情]")
        elif t == "at":
            name = str(d.get("name") or "")
            qq = str(d.get("qq") or "")
            if name and qq:
                parts.append(f"@{name}({qq})")
            elif qq:
                parts.append(f"@{qq}")
            else:
                parts.append("@")
        elif t == "reply":
            parts.append("")
    return "".join(parts)
