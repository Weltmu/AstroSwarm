STAGE_LABELS = {0: "陌生人", 1: "认识", 2: "熟悉", 3: "老熟人"}


def familiarity_stage(profile):
    if not profile:
        return 0
    days = max(1, (profile["last_seen"] - profile["first_seen"]) // 86400 + 1)
    n = profile["msg_count"]
    if days >= 30 and n >= 200:
        return 3
    if days >= 14 and n >= 80:
        return 2
    if days >= 3 and n >= 20:
        return 1
    return 0


def _is_summer_vacation(now):
    return now.month in (7, 8)


def _is_winter_vacation(now):
    return now.month in (1, 2)


def season_desc(cfg):
    now = cfg.now()
    if _is_summer_vacation(now):
        return "现在是暑假（9月1日才开学），不用上课"
    if _is_winter_vacation(now):
        return "现在是寒假，不用上课"
    return "现在是学期中，要上课"


